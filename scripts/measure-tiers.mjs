// Finds the biggest size level (3, 4, …) each game can generate and solve within 2 s, with at most
// MAX_MOVES move buttons at the start so the page stays usable. Writes src/games/tiers.js.
import { writeFileSync } from 'node:fs'
import { GAMES } from '../src/games/index.js'
import { makePosition } from '../src/engine/setup.js'

const TOP = 10
const MAX_MOVES = 60
const out = {}
for (const g of GAMES) {
  let max = 2
  for (let level = 3; level <= TOP; level++) {
    g.levels = [level]
    let ok = true
    let worst = 0
    for (const seed of [11, 22, 33]) {
      const t0 = Date.now()
      try {
        const p = makePosition(g, 3, seed * 101 + level, 15)
        ok = p.tier === 3 && g.moves(p.state).length <= MAX_MOVES
      } catch {
        ok = false
      }
      worst = Math.max(worst, Date.now() - t0)
      if (!ok || worst > 2000) break
    }
    if (!ok || worst > 2000) break
    max = level
  }
  out[g.id] = max
  console.log(g.id.padEnd(28), max)
}
writeFileSync('src/games/tiers.js', `// Generated by scripts/measure-tiers.mjs: the largest size level each game solves quickly.\nexport default ${JSON.stringify(out, null, 1)}\n`)
